func newChangeFixture() *changeFixture {
	baseSHA := strings.Repeat("a", 40)
	return &changeFixture{
		scope: githubprovider.RepositoryMutationScope{
			RepositoryID: 42, Owner: "example", Name: "repository",
			Operations: []string{githubprovider.MutationBranch, githubprovider.MutationPullRequest, githubprovider.MutationWorkflowCaller},
		},
		branches: map[string]string{"main": baseSHA},
		files: map[string]map[string]fixtureFile{
			"main": {"AGENTS.md": fileState([]byte("old\n"))},
		},
	}
}

func (fixture *changeFixture) Scope() githubprovider.RepositoryMutationScope {
	return fixture.scope
}

func (fixture *changeFixture) GetBranchRef(
	_ context.Context, owner string, name string, branch string,
) (githubprovider.RefResult, githubprovider.ResponseMeta, error) {
	if owner != fixture.scope.Owner || name != fixture.scope.Name {
		return githubprovider.RefResult{}, githubprovider.ResponseMeta{}, fmt.Errorf("scope mismatch")
	}
	sha, found := fixture.branches[branch]
	if !found {
		return githubprovider.RefResult{}, githubprovider.ResponseMeta{}, absentError()
	}
	return githubprovider.RefResult{Ref: "refs/heads/" + branch, SHA: sha}, githubprovider.ResponseMeta{}, nil
}

func (fixture *changeFixture) GetContent(
	_ context.Context, owner string, name string, path string, ref string,
) (githubprovider.ContentState, githubprovider.ResponseMeta, error) {
	if owner != fixture.scope.Owner || name != fixture.scope.Name {
		return githubprovider.ContentState{}, githubprovider.ResponseMeta{}, fmt.Errorf("scope mismatch")
	}
	file, found := fixture.files[ref][path]
	if !found {
		return githubprovider.ContentState{}, githubprovider.ResponseMeta{}, absentError()
	}
	return githubprovider.ContentState{Path: path, BlobSHA: file.sha, Content: append([]byte(nil), file.content...)}, githubprovider.ResponseMeta{}, nil
}

func (fixture *changeFixture) CompareBranches(
	_ context.Context, owner string, name string, base string, head string,
) (githubprovider.BranchComparison, githubprovider.ResponseMeta, error) {
	if owner != fixture.scope.Owner || name != fixture.scope.Name {
		return githubprovider.BranchComparison{}, githubprovider.ResponseMeta{}, fmt.Errorf("scope mismatch")
	}
	baseFiles := fixture.files[base]
	headFiles := fixture.files[head]
	paths := make([]string, 0)
	for path, headFile := range headFiles {
		baseFile, found := baseFiles[path]
		if !found || baseFile.sha != headFile.sha {
			paths = append(paths, path)
		}
	}
	sort.Strings(paths)
	files := make([]githubprovider.ComparisonFile, len(paths))
	for index, path := range paths {
		status := "modified"
		if _, found := baseFiles[path]; !found {
			status = "added"
		}
		files[index] = githubprovider.ComparisonFile{Path: path, Status: status, BlobSHA: headFiles[path].sha}
	}
	return githubprovider.BranchComparison{
		Status: "ahead", AheadBy: fixture.writes - len(fixture.pulls), BehindBy: 0,
		TotalCommits: fixture.writes - len(fixture.pulls), BaseSHA: fixture.branches[base],
		HeadSHA: fixture.branches[head], MergeBaseSHA: fixture.branches[base], Files: files,
	}, githubprovider.ResponseMeta{}, nil
}

func (fixture *changeFixture) ListOpenPullRequests(
	_ context.Context, owner string, name string, head string, base string,
) ([]githubprovider.DraftPullRequest, githubprovider.ResponseMeta, error) {
	if owner != fixture.scope.Owner || name != fixture.scope.Name {
		return nil, githubprovider.ResponseMeta{}, fmt.Errorf("scope mismatch")
	}
	return append([]githubprovider.DraftPullRequest(nil), fixture.pulls...), githubprovider.ResponseMeta{}, nil
}

func (fixture *changeFixture) CreateBranch(
	_ context.Context, branch string, fromSHA string,
) (githubprovider.RefResult, githubprovider.MutationMeta, error) {
	if _, exists := fixture.branches[branch]; exists || fixture.branches["main"] != fromSHA {
		return githubprovider.RefResult{}, githubprovider.MutationMeta{}, fmt.Errorf("branch create precondition")
	}
	fixture.branches[branch] = fromSHA
	fixture.files[branch] = cloneFiles(fixture.files["main"])
	fixture.writes++
	return githubprovider.RefResult{Ref: "refs/heads/" + branch, SHA: fromSHA}, fixture.meta(), nil
}

func (fixture *changeFixture) FastForwardBranch(
	_ context.Context, branch string, target string,
) (githubprovider.RefResult, githubprovider.MutationMeta, error) {
	if _, exists := fixture.branches[branch]; !exists {
		return githubprovider.RefResult{}, githubprovider.MutationMeta{}, fmt.Errorf("branch missing")
	}
	fixture.branches[branch] = target
	fixture.writes++
	return githubprovider.RefResult{Ref: "refs/heads/" + branch, SHA: target}, fixture.meta(), nil
}

func (fixture *changeFixture) PutContent(
	_ context.Context, update githubprovider.ContentUpdate,
) (githubprovider.ContentResult, githubprovider.MutationMeta, error) {
	current, found := fixture.files[update.Branch][update.Path]
	if update.ExpectedSHA != "" && (!found || current.sha != update.ExpectedSHA) {
		return githubprovider.ContentResult{}, githubprovider.MutationMeta{}, fmt.Errorf("content precondition")
	}
	file := fileState(update.Content)
	fixture.files[update.Branch][update.Path] = file
	fixture.writes++
	commitSHA := oid(fmt.Sprintf("commit-%d", fixture.writes))
	fixture.branches[update.Branch] = commitSHA
	return githubprovider.ContentResult{Path: update.Path, BlobSHA: file.sha, CommitSHA: commitSHA}, fixture.meta(), nil
}

func (fixture *changeFixture) CreateDraftPullRequest(
	_ context.Context, title string, body string, head string, base string,
) (githubprovider.DraftPullRequest, githubprovider.MutationMeta, error) {
	fixture.writes++
	pull := githubprovider.DraftPullRequest{
		Number: 1, ID: 2, HTMLURL: "https://github.com/example/repository/pull/1",
		HeadRef: head, HeadSHA: fixture.branches[head], BaseRef: base,
		Draft: true, State: "open", Title: title, Body: body,
	}
	fixture.pulls = []githubprovider.DraftPullRequest{pull}
	return pull, fixture.meta(), nil
}

func (fixture *changeFixture) meta() githubprovider.MutationMeta {
	return githubprovider.MutationMeta{RepositoryID: 42, StatusCode: 200, RequestID: "fixture"}
}

func encodedContent(path, state, expected, finalStatus string, content []byte) *ContentChange {
	return &ContentChange{
		Path: path, Message: "chore: update " + path, ExpectedState: state,
		ExpectedSHA: expected, FinalStatus: finalStatus,
		ContentBase64: base64.StdEncoding.EncodeToString(content),
		ContentDigest: DigestContent(content),
	}
}

func changeStep(id, action string, parameters OperationParameters) operations.Step {
	return operations.Step{
		StepID: id, RepositoryID: "repo_01JEXAMPZ0000000000000000C", Action: action,
		RequiresApproval: true, Compensation: operations.Compensation{Mode: "manual"},
		Parameters: Parameters(parameters),
	}
}

func fileState(content []byte) fixtureFile {
	return fixtureFile{sha: oid("blob\x00" + string(content)), content: append([]byte(nil), content...)}
}

func cloneFiles(values map[string]fixtureFile) map[string]fixtureFile {
	result := make(map[string]fixtureFile, len(values))
	for path, file := range values {
		result[path] = fixtureFile{sha: file.sha, content: append([]byte(nil), file.content...)}
	}
	return result
}

func oid(value string) string {
	digest := sha1.Sum([]byte(value))
	return fmt.Sprintf("%x", digest[:])
}

func absentError() error {
	return &githubprovider.APIError{Kind: githubprovider.ErrorNotFoundOrInaccessible, StatusCode: 404}
}

func mustJSON(t *testing.T, value any) []byte {
	t.Helper()
	raw, err := json.Marshal(value)
	if err != nil {
		t.Fatal(err)
	}
	return raw
}
