type fixtureFile struct {
	sha     string
	content []byte
}

type changeFixture struct {
	scope    githubprovider.RepositoryMutationScope
	branches map[string]string
	files    map[string]map[string]fixtureFile
	pulls    []githubprovider.DraftPullRequest
	writes   int
}

func TestHandlerAppliesAndVerifiesExactMultiFileDraftPR(t *testing.T) {
	fixture := newChangeFixture()
	baseSHA := fixture.branches["main"]
	files := []PlannedFile{
		{Path: ".github/workflows/gds.yml", Status: "added", ContentDigest: DigestContent([]byte("name: gds\n"))},
		{Path: "AGENTS.md", Status: "modified", ContentDigest: DigestContent([]byte("generated\n"))},
	}
	scope := Scope{
		ReadInstallationID: "installation:read", MutationCapabilityID: "mutation:write",
		ProviderRepositoryID: 42, Owner: "example", Name: "repository",
		BaseBranch: "main", BaseSHA: baseSHA, HeadBranch: "gds/change",
	}
	changeDigest, err := ChangeSetDigest(scope, files)
	if err != nil {
		t.Fatal(err)
	}
	scope.ChangeSetDigest = changeDigest
	steps := []operations.Step{
		changeStep("branch", BranchAction, OperationParameters{
			Scope: scope, Branch: &BranchChange{ExpectedState: "missing", TargetSHA: baseSHA},
		}),
		changeStep("workflow", ContentAction, OperationParameters{
			Scope: scope, Content: encodedContent(
				".github/workflows/gds.yml", "missing", "", "added", []byte("name: gds\n"),
			),
		}),
		changeStep("agents", ContentAction, OperationParameters{
			Scope: scope, Content: encodedContent(
				"AGENTS.md", "regular", fixture.files["main"]["AGENTS.md"].sha,
				"modified", []byte("generated\n"),
			),
		}),
		changeStep("pull-request", DraftPRAction, OperationParameters{
			Scope: scope, PullRequest: &PullRequestChange{
				Title: "chore: update GDS projections", Body: "Generated by GDS.", Files: files,
			},
		}),
	}
	schemas, err := validation.NewSchemaSet()
	if err != nil {
		t.Fatal(err)
	}
	now := time.Date(2026, 7, 11, 5, 0, 0, 0, time.UTC)
	plan, err := operations.NewPlan(
		"plan_01KX7BV07RHD6KRA4Z4J0KCHGR", now, now.Add(15*time.Minute),
		operations.PlanInput{
			Operation: "publish-github-change",
			Actor:     operations.Actor{Type: "agent-session", SessionID: "test-session"},
			Preconditions: []operations.Precondition{{
				RepositoryID: "repo_01JEXAMPZ0000000000000000C", HeadOID: baseSHA,
				ManifestDigest: "sha256:" + strings.Repeat("a", 64),
				PolicyDigest:   "sha256:" + strings.Repeat("b", 64),
			}},
			Steps: steps, ApprovalClass: "github-change-write",
		},
	)
	if err != nil || len(plan.Validate(schemas)) != 0 {
		t.Fatalf("plan err=%v findings=%#v", err, plan.Validate(schemas))
	}
	if err := ValidatePlan(plan); err != nil {
		t.Fatal(err)
	}
	evidence := make([]any, len(steps))
	for index, step := range steps {
		handler := &Handler{Reader: fixture, Writer: fixture, Action: step.Action}
		result, err := handler.Apply(context.Background(), step)
		if err != nil {
			t.Fatalf("apply %s: %v", step.Action, err)
		}
		evidence[index] = result.After
	}
	if fixture.writes != 4 || len(fixture.pulls) != 1 {
		t.Fatalf("writes=%d pulls=%d", fixture.writes, len(fixture.pulls))
	}
	for index, step := range steps {
		handler := &Handler{Reader: fixture, Scope: fixture.scope, Action: step.Action}
		raw := mustJSON(t, evidence[index])
		if err := handler.Verify(context.Background(), step, raw); err != nil {
			t.Fatalf("verify %s: %v", step.Action, err)
		}
	}
}

func TestHandlerBlocksStaleContentWithoutWrite(t *testing.T) {
	fixture := newChangeFixture()
	scope := Scope{
		ReadInstallationID: "installation:read", MutationCapabilityID: "mutation:write",
		ProviderRepositoryID: 42, Owner: "example", Name: "repository",
		BaseBranch: "main", BaseSHA: fixture.branches["main"], HeadBranch: "gds/change",
	}
	scope.ChangeSetDigest = "sha256:" + strings.Repeat("a", 64)
	fixture.branches[scope.HeadBranch] = scope.BaseSHA
	fixture.files[scope.HeadBranch] = cloneFiles(fixture.files["main"])
	change := encodedContent("AGENTS.md", "regular", strings.Repeat("f", 40), "modified", []byte("generated\n"))
	step := changeStep("agents", ContentAction, OperationParameters{Scope: scope, Content: change})
	handler := &Handler{Reader: fixture, Writer: fixture, Action: ContentAction}
	if _, err := handler.Apply(context.Background(), step); err == nil || fixture.writes != 0 {
		t.Fatalf("err=%v writes=%d", err, fixture.writes)
	}
}

